"""
CONTRA eval runner — scores every fixture case, writes the accuracy summary.

    python -m contra.eval.run_evals
    python -m contra.eval.run_evals --pass-k 3   # stability: run each case k times

Produces docs/eval-summary.md (submission deliverable #6 source) and a
machine-readable eval_results.json. Aggregate precision/recall/FP across cases.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from .grader import grade_case, CaseScore

FIXTURES = Path(__file__).resolve().parent.parent / "fixtures"


def discover_cases() -> list[Path]:
    return sorted(p for p in FIXTURES.iterdir()
                  if p.is_dir() and (p / "ground_truth.json").exists())


def run(pass_k: int = 1) -> list[CaseScore]:
    scores: list[CaseScore] = []
    for case in discover_cases():
        # pass^k stability: case must pass every one of k runs to count as pass.
        runs = [grade_case(case) for _ in range(pass_k)]
        last = runs[-1]
        last_stable = all(r.passed() for r in runs)
        last.matched = last.matched  # keep
        scores.append((last, last_stable))  # type: ignore
    return scores  # type: ignore


def render(scores) -> str:
    lines = ["# CONTRA Accuracy Report", "",
             "Auto-generated by `python -m contra.eval.run_evals`. Offline fixtures.", "",
             "| Case | Expected | Detected | TP | FP | FN | Precision | Recall | Pass |",
             "|------|----------|----------|----|----|----|-----------|--------|------|"]
    tp = fp = fn = exp = det = 0
    all_pass = True
    for s, stable in scores:
        ok = "PASS" if (s.passed() and stable) else "FAIL"
        all_pass = all_pass and s.passed() and stable
        lines.append(f"| {s.case} | {s.expected} | {s.detected} | {s.true_positives} "
                     f"| {s.false_positives} | {s.false_negatives} | {s.precision} "
                     f"| {s.recall} | {ok} |")
        tp += s.true_positives; fp += s.false_positives; fn += s.false_negatives
        exp += s.expected; det += s.detected
    prec = round(tp / det, 3) if det else 1.0
    rec = round(tp / exp, 3) if exp else 1.0
    lines += ["",
              f"**Aggregate** — TP {tp}, FP {fp}, FN {fn} · "
              f"precision {prec} · recall {rec} · "
              f"overall {'PASS' if all_pass else 'FAIL'}", ""]
    # per-case detail
    for s, _ in scores:
        if s.missed or s.spurious:
            lines.append(f"- {s.case}: missed={s.missed} spurious={s.spurious}")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pass-k", type=int, default=1)
    ap.add_argument("--out", default="docs/eval-summary.md")
    args = ap.parse_args()

    scores = run(args.pass_k)
    report = render(scores)
    print(report)

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report, encoding="utf-8")
    Path("docs/eval_results.json").write_text(
        json.dumps([s.to_dict() for s, _ in scores], indent=2), encoding="utf-8")
    print(f"\nwritten: {out} + docs/eval_results.json")

    # exit non-zero if any case fails — usable as a CI gate
    failed = [s.case for s, stable in scores if not (s.passed() and stable)]
    if failed:
        raise SystemExit(f"eval FAIL: {failed}")


if __name__ == "__main__":
    main()
